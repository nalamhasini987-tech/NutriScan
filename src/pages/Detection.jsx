
import { useState } from 'react'
import './Detection.css'

function Detection() {
  const [image, setImage] = useState(null)
  const [preview, setPreview] = useState(null)
  const [result, setResult] = useState(null)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState('')

  const handleImage = (event) => {
    const file = event.target.files[0]

    if (!file) return

    if (!file.type.startsWith('image/')) {
      setError('Please upload a valid image.')
      return
    }

    setImage(file)
    setPreview(URL.createObjectURL(file))
    setResult(null)
    setError('')
  }

  const handlePredict = async () => {
    if (!image) {
      setError('Please upload an image first.')
      return
    }

    setLoading(true)
    setError('')
    setResult(null)

    try {
      // Backend URL will be configured during integration.
    const API_URL = import.meta.env.VITE_API_URL;
      if (!API_URL) {
        throw new Error('Backend URL is not configured yet.')
      }

      const formData = new FormData()
      formData.append('file', image)

      const response = await fetch(`${API_URL}/predict`, {
        method: 'POST',
        body: formData
      })

      if (!response.ok) {
        throw new Error('Prediction failed. Please try again.')
      }

      const data = await response.json()
      setResult(data)

    } catch (err) {
      setError(err.message)
    } finally {
      setLoading(false)
    }
  }

  const removeImage = () => {
    if (preview) URL.revokeObjectURL(preview)
    setImage(null)
    setPreview(null)
    setResult(null)
    setError('')
  }

  return (
    <div className="detection-page">

      <section className="detection-hero">
        <span className="detection-badge">
          AI POWERED IMAGE ANALYSIS
        </span>

        <h1>
          Nutritional Deficiency
          <span> Detection</span>
        </h1>

        <p>
          Upload an image and explore the prediction
          generated by our experimental AI model.
        </p>
      </section>

      <section className="detection-content">

        <div className="detection-instructions">
          <h2>Analyze Your Image</h2>
          <p>
            Follow these simple steps to explore your
            image classification result.
          </p>

          <div className="instruction-list">
            <div className="instruction-item">
              <span>01</span>
              <div>
                <h3>Upload Image</h3>
                <p>Select an image from your device.</p>
              </div>
            </div>

            <div className="instruction-item">
              <span>02</span>
              <div>
                <h3>Analyze Image</h3>
                <p>Submit the image to the AI model.</p>
              </div>
            </div>

            <div className="instruction-item">
              <span>03</span>
              <div>
                <h3>View Prediction</h3>
                <p>Explore the predicted classification.</p>
              </div>
            </div>
          </div>
        </div>

        <div className="detection-upload-card">

          <div className="upload-card-heading">
            <h2>Upload Your Image</h2>
            <p>Choose a JPG, JPEG or PNG image</p>
          </div>

          <label className="detection-dropzone">

            {preview ? (
              <img
                src={preview}
                alt="Uploaded preview"
                className="detection-preview"
              />
            ) : (
              <>
                <div className="detection-upload-icon">
                  ↑
                </div>

                <h3>Drag your image here</h3>
                <p>or click to browse files</p>
                <span>JPG · JPEG · PNG</span>
              </>
            )}

            <input
              type="file"
              accept="image/png,image/jpeg"
              onChange={handleImage}
              hidden
            />

          </label>

          {image && (
            <div className="selected-file">
              <span>📄 {image.name}</span>

              <button
                type="button"
                onClick={removeImage}
              >
                Remove
              </button>
            </div>
          )}

          <button
            className="detection-submit"
            onClick={handlePredict}
            disabled={!image || loading}
          >
            {loading ? 'Analyzing Image...' : 'Analyze Image →'}
          </button>

          {error && (
            <div className="detection-error">
              {error}
            </div>
          )}

          {result && (
            <div className="detection-result">
              <span>MODEL PREDICTION</span>
              <h2>{result.predicted_class}</h2>
              <p>
                Model score: {result.model_score}%
              </p>
              <small>{result.note}</small>
            </div>
          )}

          <p className="upload-disclaimer">
            Your image is submitted for experimental
            classification. This is not a medical diagnosis.
          </p>

        </div>
      </section>

    </div>
  )
}

export default Detection
